import React, { useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { AlarmClock, ArrowUpRight, BellOff, CheckCheck, Play, Settings2 } from 'lucide-react';
import { PageHead } from '../components/AppShell';
import { Badge, Drawer, EmptyState, Field, Notice, PromptDialog, StatusBadge, Tabs } from '../components/ui';
import { useStore } from '../store/store';
import { ROLE_LABELS } from '../types';
import type { EscalationRule, Notification } from '../types';
import { fmtDate, fmtDateTime, daysBetween } from '../lib/dates';
import { can } from '../lib/perms';

type ViewTab = 'all' | 'unread' | 'deadlines' | 'overdue' | 'escalated' | 'resolved';

export default function NotificationsPage() {
    const { state, user, now, toast, markNotificationRead, markAllRead, acknowledgeNotification, resolveNotification, evaluateDeadlines, saveEscalationRule } =
        useStore();
    const navigate = useNavigate();
    const [tab, setTab] = useState<ViewTab>('all');
    const [severity, setSeverity] = useState('');
    const [q, setQ] = useState('');
    const [detail, setDetail] = useState<Notification | null>(null);
    const [resolveFor, setResolveFor] = useState<Notification | null>(null);
    const [configOpen, setConfigOpen] = useState(false);

    const visible = useMemo(() => {
        let rows = state.notifications;
        if (user?.role !== 'admin') {
            rows = rows.filter(
                (n) =>
                    n.recipientRole === user?.role ||
                    n.recipientRole === 'all' ||
                    (user?.role === 'institution' && n.recipientName === state.institutions.find((i) => i.id === user.institutionId)?.name),
            );
        }
        if (severity) rows = rows.filter((n) => n.severity === severity);
        if (q.trim()) {
            const term = q.trim().toLowerCase();
            rows = rows.filter((n) => n.title.toLowerCase().includes(term) || n.body.toLowerCase().includes(term) || n.entityId.toLowerCase().includes(term));
        }
        if (tab === 'unread') rows = rows.filter((n) => !n.read && !n.resolvedAt);
        if (tab === 'deadlines') rows = rows.filter((n) => !n.resolvedAt && n.deadline && daysBetween(now, n.deadline) >= 0 && daysBetween(now, n.deadline) <= 30);
        if (tab === 'overdue') rows = rows.filter((n) => !n.resolvedAt && n.deadline && daysBetween(now, n.deadline) < 0);
        if (tab === 'escalated') rows = rows.filter((n) => !n.resolvedAt && n.escalationLevel > 0);
        if (tab === 'resolved') rows = rows.filter((n) => !!n.resolvedAt);
        return [...rows].sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
    }, [state.notifications, state.institutions, user, severity, q, tab, now]);

    const counts = {
        all: state.notifications.length,
        unread: state.notifications.filter((n) => !n.read && !n.resolvedAt).length,
        deadlines: state.notifications.filter((n) => !n.resolvedAt && n.deadline && daysBetween(now, n.deadline) >= 0 && daysBetween(now, n.deadline) <= 30).length,
        overdue: state.notifications.filter((n) => !n.resolvedAt && n.deadline && daysBetween(now, n.deadline) < 0).length,
        escalated: state.notifications.filter((n) => !n.resolvedAt && n.escalationLevel > 0).length,
        resolved: state.notifications.filter((n) => !!n.resolvedAt).length,
    };

    const openEntity = (n: Notification) => {
        if (n.entityType === 'application') navigate(`/applications/${encodeURIComponent(n.entityId)}`);
        else if (n.entityType === 'document') navigate(`/documents?q=${encodeURIComponent(n.entityId)}`);
        else if (n.entityType === 'undertaking') navigate(`/compliance?q=${encodeURIComponent(n.entityId)}`);
        else navigate('/evc');
    };

    return (
        <>
            <PageHead
                title="Notifications &amp; escalations"
                description="Alerts generated by the simulated deadline engine over the shared sample records. Nothing is sent externally — every notification is an in-app record."
                actions={
                    <>
                        <button
                            className="btn"
                            onClick={() => {
                                markAllRead();
                                toast({ title: 'All notifications marked read', body: `${counts.unread} alert(s) updated.`, tone: 'success' });
                            }}
                            disabled={counts.unread === 0}
                        >
                            <CheckCheck size={15} /> Mark all read
                        </button>
                        <button
                            className="btn btn--primary"
                            onClick={() => {
                                evaluateDeadlines();
                                toast({ title: 'Deadline engine executed', body: 'Records re-evaluated; new or escalated alerts appear at the top.', tone: 'success' });
                            }}
                        >
                            <Play size={15} /> Run deadline evaluation
                        </button>
                        {can(user, 'settings.manage') && (
                            <button className="btn" onClick={() => setConfigOpen(true)}>
                                <Settings2 size={15} /> Escalation rules
                            </button>
                        )}
                    </>
                }
            />

            <div className="card">
                <div className="card__hd">
                    <Tabs<ViewTab>
                        tabs={[
                            { id: 'all', label: 'All' },
                            { id: 'unread', label: 'Unread' },
                            { id: 'deadlines', label: 'Upcoming deadlines' },
                            { id: 'overdue', label: 'Overdue' },
                            { id: 'escalated', label: 'Escalated' },
                            { id: 'resolved', label: 'Resolved' },
                        ]}
                        active={tab}
                        onChange={setTab}
                        counts={counts}
                    />
                    <div className="row gap8 wrap">
                        <input className="input" style={{ width: 220, fontSize: 12 }} placeholder="Search alerts…" value={q} onChange={(e) => setQ(e.target.value)} aria-label="Search notifications" />
                        <select className="select" style={{ width: 140, fontSize: 12 }} value={severity} onChange={(e) => setSeverity(e.target.value)} aria-label="Severity">
                            <option value="">All severities</option>
                            <option value="Info">Info</option>
                            <option value="Warning">Warning</option>
                            <option value="Critical">Critical</option>
                        </select>
                    </div>
                </div>

                <div className="card__bd card__bd--tight">
                    {visible.length === 0 && (
                        <EmptyState
                            title="No notifications in this view"
                            body="Change the tab or run the deadline engine to generate alerts from the sample records."
                            action={
                                <button className="btn btn--sm" onClick={() => { setTab('all'); setSeverity(''); setQ(''); }}>
                                    Show all notifications
                                </button>
                            }
                        />
                    )}
                    {visible.map((n) => {
                        const late = n.deadline ? daysBetween(now, n.deadline) : null;
                        return (
                            <div key={n.id} className="listrow" style={{ alignItems: 'flex-start', background: n.read ? undefined : 'var(--brand-50)' }}>
                                {!n.read && <span className="unread-dot" />}
                                <div className="grow" style={{ minWidth: 0 }}>
                                    <div className="row between gap8 wrap">
                                        <div className="row gap8 wrap">
                                            <span className="small strong" style={{ color: 'var(--text-strong)' }}>{n.title}</span>
                                            <StatusBadge status={n.severity} />
                                            {n.escalationLevel > 0 && <Badge tone="red">Level {n.escalationLevel}</Badge>}
                                            {n.resolvedAt && <Badge tone="green">Resolved</Badge>}
                                            {n.acknowledgedAt && !n.resolvedAt && <Badge tone="navy">Acknowledged</Badge>}
                                        </div>
                                        <span className="tiny muted nowrap">{fmtDateTime(n.createdAt)}</span>
                                    </div>
                                    <div className="small muted mt4">{n.body}</div>
                                    <div className="row gap12 wrap mt6 tiny muted">
                                        <span>To: {n.recipientName} ({n.recipientRole === 'all' ? 'all roles' : ROLE_LABELS[n.recipientRole]})</span>
                                        <span>Trigger: {n.trigger}</span>
                                        {n.deadline && (
                                            <span>
                                                Deadline: {fmtDate(n.deadline)}
                                                {late !== null && (late < 0 ? ` · ${Math.abs(late)} d overdue` : ` · ${late} d remaining`)}
                                            </span>
                                        )}
                                        <span>Delivery: {n.delivery}</span>
                                        <span className="mono">{n.entityId}</span>
                                    </div>
                                    <div className="row gap6 wrap mt8">
                                        <button className="btn btn--sm" onClick={() => openEntity(n)}>
                                            <ArrowUpRight size={12} /> Open related case
                                        </button>
                                        {!n.read && (
                                            <button className="btn btn--sm" onClick={() => markNotificationRead(n.id)}>
                                                Mark read
                                            </button>
                                        )}
                                        {!n.acknowledgedAt && !n.resolvedAt && (
                                            <button
                                                className="btn btn--sm"
                                                onClick={() => {
                                                    acknowledgeNotification(n.id);
                                                    toast({ title: 'Alert acknowledged', body: 'The acknowledgement was recorded with your name.', tone: 'success' });
                                                }}
                                            >
                                                Acknowledge
                                            </button>
                                        )}
                                        {!n.resolvedAt && can(user, 'notification.resolve') && (
                                            <button className="btn btn--sm btn--success" onClick={() => setResolveFor(n)}>
                                                Resolve
                                            </button>
                                        )}
                                        <button className="btn btn--sm btn--ghost" onClick={() => setDetail(n)}>
                                            Escalation history ({n.escalationHistory.length})
                                        </button>
                                    </div>
                                </div>
                            </div>
                        );
                    })}
                </div>
            </div>

            <div className="card mt16">
                <div className="card__hd">
                    <div>
                        <h2>Simulated deadline engine</h2>
                        <p>Evaluates applications, EVC visits, undertakings and documents against the configured rules.</p>
                    </div>
                </div>
                <div className="card__bd col gap10">
                    <div className="grid-auto" style={{ gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))' }}>
                        {state.escalationRules.map((r) => (
                            <div key={r.id} className="card card--flat">
                                <div className="card__bd">
                                    <div className="row between gap8">
                                        <span className="small strong">{r.name}</span>
                                        <Badge tone={r.enabled ? 'green' : 'slate'}>{r.enabled ? 'Enabled' : 'Disabled'}</Badge>
                                    </div>
                                    <div className="tiny muted mt4">
                                        Trigger: {r.trigger.replace(/_/g, ' ')} · threshold {r.thresholdDays} d
                                    </div>
                                    <div className="tiny muted mt4">
                                        {r.levels.map((l) => `L${l.level} after ${l.afterDays}d → ${l.recipients.map((x) => ROLE_LABELS[x]).join(', ')}`).join(' · ')}
                                    </div>
                                </div>
                            </div>
                        ))}
                    </div>
                    <Notice tone="warn">
                        Alerts are generated locally in the browser from sample records. No email, SMS or push notification is sent, and thresholds are
                        prototype configuration values.
                    </Notice>
                </div>
            </div>

            <PromptDialog
                open={!!resolveFor}
                onClose={() => setResolveFor(null)}
                title="Resolve alert"
                subtitle={resolveFor?.title}
                label="How was this resolved?"
                placeholder="e.g. Scrutiny completed and the application forwarded; the overdue flag no longer applies…"
                submitLabel="Resolve alert"
                hint="The resolution note, your name and the timestamp are written to the escalation history and audit trail."
                onSubmit={(note) => {
                    if (!resolveFor) return;
                    const res = resolveNotification(resolveFor.id, note);
                    toast(res.ok ? { title: 'Alert resolved', body: 'Escalation history updated.', tone: 'success' } : { title: 'Could not resolve', body: res.error, tone: 'error' });
                }}
            />

            <Drawer
                open={!!detail}
                onClose={() => setDetail(null)}
                title="Escalation history"
                subtitle={detail?.title}
                footer={<button className="btn" onClick={() => setDetail(null)}>Close</button>}
            >
                {detail && (
                    <div className="col gap16">
                        <dl className="kv">
                            <dt>Related record</dt>
                            <dd className="mono">{detail.entityId}</dd>
                            <dt>Recipient</dt>
                            <dd>{detail.recipientName}</dd>
                            <dt>Trigger</dt>
                            <dd>{detail.trigger}</dd>
                            <dt>Created</dt>
                            <dd>{fmtDateTime(detail.createdAt)}</dd>
                            <dt>Current level</dt>
                            <dd>{detail.escalationLevel === 0 ? 'Not escalated' : `Level ${detail.escalationLevel}`}</dd>
                            <dt>Deadline</dt>
                            <dd>{detail.deadline ? fmtDate(detail.deadline) : '—'}</dd>
                            <dt>Delivery</dt>
                            <dd>{detail.delivery}</dd>
                            {detail.resolutionNote && (
                                <>
                                    <dt>Resolution</dt>
                                    <dd>{detail.resolutionNote}</dd>
                                </>
                            )}
                        </dl>
                        {detail.escalationHistory.length === 0 ? (
                            <EmptyState title="No escalation events" body="This alert has not been escalated under the configured rules." />
                        ) : (
                            <div className="timeline">
                                {detail.escalationHistory.map((h, i) => (
                                    <div key={i} className="tl-item">
                                        <div className="tl-rail">
                                            <div className="tl-node tl-node--current">{h.level}</div>
                                            {i < detail.escalationHistory.length - 1 && <div className="tl-line tl-line--done" />}
                                        </div>
                                        <div className="tl-body">
                                            <div className="tl-title">Level {h.level} — {h.to}</div>
                                            <div className="tl-meta">{fmtDateTime(h.at)}</div>
                                            <div className="tl-card">{h.note}</div>
                                        </div>
                                    </div>
                                ))}
                            </div>
                        )}
                        <Notice tone="slate">
                            <AlarmClock size={13} style={{ verticalAlign: 'middle', marginRight: 4 }} />
                            Escalation is driven entirely by the configurable rules below; nothing here implies an official AICTE escalation policy.
                        </Notice>
                    </div>
                )}
            </Drawer>

            <EscalationConfigDrawer
                open={configOpen}
                onClose={() => setConfigOpen(false)}
                rules={state.escalationRules}
                onSave={(rule) => {
                    saveEscalationRule(rule);
                    toast({ title: 'Escalation rule updated', body: `${rule.name} saved.`, tone: 'success' });
                }}
            />
        </>
    );
}

function EscalationConfigDrawer({
    open,
    onClose,
    rules,
    onSave,
}: {
    open: boolean;
    onClose: () => void;
    rules: EscalationRule[];
    onSave: (rule: EscalationRule) => void;
}) {
    const [drafts, setDrafts] = useState<EscalationRule[]>([]);

    React.useEffect(() => {
        if (open) setDrafts(JSON.parse(JSON.stringify(rules)));
    }, [open, rules]);

    const update = (idx: number, patch: Partial<EscalationRule>) =>
        setDrafts((prev) => prev.map((r, i) => (i === idx ? { ...r, ...patch } : r)));

    return (
        <Drawer
            open={open}
            onClose={onClose}
            wide
            title="Escalation rules"
            subtitle="Thresholds and escalation levels are prototype configuration values, not official policy."
            footer={
                <>
                    <button className="btn" onClick={onClose}>Close</button>
                    <button
                        className="btn btn--primary"
                        onClick={() => {
                            drafts.forEach((r) => onSave(r));
                            onClose();
                        }}
                    >
                        Save all rules
                    </button>
                </>
            }
        >
            <div className="col gap16">
                {drafts.map((r, idx) => (
                    <div key={r.id} className="card card--flat">
                        <div className="card__bd col gap10">
                            <div className="row between gap8 wrap">
                                <label className="checkline">
                                    <input type="checkbox" checked={r.enabled} onChange={(e) => update(idx, { enabled: e.target.checked })} />
                                    <span className="strong small">{r.name}</span>
                                </label>
                                <Badge tone="slate">{r.trigger.replace(/_/g, ' ')}</Badge>
                            </div>
                            <div className="row gap8 wrap">
                                <Field label="Threshold (days)">
                                    <input
                                        type="number"
                                        min={0}
                                        className="input"
                                        style={{ width: 110 }}
                                        value={r.thresholdDays}
                                        onChange={(e) => update(idx, { thresholdDays: Number(e.target.value) })}
                                    />
                                </Field>
                                {r.levels.map((l, li) => (
                                    <Field key={li} label={`Level ${l.level} after (days)`}>
                                        <input
                                            type="number"
                                            min={0}
                                            className="input"
                                            style={{ width: 110 }}
                                            value={l.afterDays}
                                            onChange={(e) =>
                                                update(idx, {
                                                    levels: r.levels.map((x, i) => (i === li ? { ...x, afterDays: Number(e.target.value) } : x)),
                                                })
                                            }
                                        />
                                    </Field>
                                ))}
                            </div>
                            <div className="tiny muted">
                                Recipients: {r.levels.map((l) => `L${l.level}: ${l.recipients.map((x) => ROLE_LABELS[x]).join(', ')}`).join(' · ')}
                            </div>
                        </div>
                    </div>
                ))}
                <Notice tone="info">
                    Disabling a rule stops the deadline engine from creating that class of alert. Existing alerts stay in the list until resolved.
                </Notice>
            </div>
        </Drawer>
    );
}
